export function matchIcon(item: string): IconKey {
  const t = item.toLowerCase().replace(/\s+/g, "");
  for (const [icon, words] of KEYWORDS) {
    if (words.some((w) => t.includes(w.toLowerCase().replace(/\s+/g, "")))) return icon;
  }
  return "box";
}
